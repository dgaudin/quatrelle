//! `cargo xtask icons`: render Quatrelle's app icon into `assets/app-icon/`.
//!
//! The icon is drawn here, from the geometry below, so it is Quatrelle's own and every size comes
//! from one definition: a rounded teal square with a white envelope. Each pixel's coverage comes
//! from signed distances (one sample per pixel, antialiased analytically), so small sizes stay
//! sharp without supersampling.
//!
//! Writes the hicolor PNGs (16–512 px, Linux and FreeBSD), a 1024 px master, an SVG of the same
//! drawing, `quatrelle.ico` (Windows) and `quatrelle.icns` (macOS). The outputs are committed, so
//! builds and packaging never run this.
//!
//! A picture of the owner's own, `assets/icon.png` (square), is used instead of the drawing when
//! it's there: every size is sampled down from it, and the scalable SVG carries it. The drawing
//! below is what the app ships with until then.

use std::path::Path;

pub const ID: &str = "ai.storyteller.quatrelle";
const HICOLOR: &[u32] = &[16, 24, 32, 48, 64, 128, 256, 512];
const ICO: &[u32] = &[16, 24, 32, 48, 64, 128, 256];

// Geometry, in units of the icon's side (0..1).
const MARGIN: f32 = 0.0625;
const RADIUS: f32 = 0.2;
const ENV_CX: f32 = 0.5;
const ENV_CY: f32 = 0.52;
const ENV_HW: f32 = 0.30;
const ENV_HH: f32 = 0.205;
const ENV_R: f32 = 0.045;
const FLAP_Y: f32 = 0.575;
const STROKE: f32 = 0.05;
// Colours: Quatrelle teal (theme::APP_COLOR, #0E7C86) lightened at the top.
const TOP: [f32; 3] = [0x16 as f32, 0x9a as f32, 0xa6 as f32];
const BOTTOM: [f32; 3] = [0x0b as f32, 0x66 as f32, 0x70 as f32];

/// Distance from `p` to a rounded box centred at `c` with half-size `h` and corner radius `r`.
fn rounded_box(p: (f32, f32), c: (f32, f32), h: (f32, f32), r: f32) -> f32 {
    let qx = (p.0 - c.0).abs() - h.0 + r;
    let qy = (p.1 - c.1).abs() - h.1 + r;
    let outside = qx.max(0.0).hypot(qy.max(0.0));
    outside + qx.max(qy).min(0.0) - r
}

/// Distance from `p` to the segment `a`–`b`.
fn segment(p: (f32, f32), a: (f32, f32), b: (f32, f32)) -> f32 {
    let (px, py, bx, by) = (p.0 - a.0, p.1 - a.1, b.0 - a.0, b.1 - a.1);
    let t = ((px * bx + py * by) / (bx * bx + by * by)).clamp(0.0, 1.0);
    (px - bx * t).hypot(py - by * t)
}

/// Coverage (0..1) of a pixel whose centre is `d` (in pixels) from a shape's edge.
fn coverage(d: f32) -> f32 {
    (0.5 - d).clamp(0.0, 1.0)
}

/// Paint `src` with coverage `a` over the straight-alpha pixel `dst`.
fn over(dst: &mut [f32; 4], src: [f32; 3], a: f32) {
    let out_a = a + dst[3] * (1.0 - a);
    if out_a <= 0.0 {
        return;
    }
    for i in 0..3 {
        dst[i] = (src[i] * a + dst[i] * dst[3] * (1.0 - a)) / out_a;
    }
    dst[3] = out_a;
}

/// The icon at `size` × `size`, as straight-alpha RGBA bytes.
pub fn render(size: u32) -> Vec<u8> {
    let n = size as f32;
    let px = 1.0 / n;
    // At 16–24 px a proportional stroke would vanish; keep it at least ~1.4 px.
    let stroke = STROKE.max(1.4 * px);
    let flap_l = (ENV_CX - ENV_HW + ENV_R * 0.5, ENV_CY - ENV_HH + ENV_R * 0.5);
    let flap_r = (ENV_CX + ENV_HW - ENV_R * 0.5, ENV_CY - ENV_HH + ENV_R * 0.5);
    let flap_m = (ENV_CX, FLAP_Y);
    let mut out = Vec::with_capacity((size * size * 4) as usize);
    for y in 0..size {
        for x in 0..size {
            let p = ((x as f32 + 0.5) * px, (y as f32 + 0.5) * px);
            let mut c = [0.0f32; 4];
            let bg = coverage(rounded_box(p, (0.5, 0.5), (0.5 - MARGIN, 0.5 - MARGIN), RADIUS) * n);
            let t = ((p.1 - MARGIN) / (1.0 - 2.0 * MARGIN)).clamp(0.0, 1.0);
            let teal = [TOP[0] + (BOTTOM[0] - TOP[0]) * t, TOP[1] + (BOTTOM[1] - TOP[1]) * t, TOP[2] + (BOTTOM[2] - TOP[2]) * t];
            over(&mut c, teal, bg);
            let body = coverage(rounded_box(p, (ENV_CX, ENV_CY), (ENV_HW, ENV_HH), ENV_R) * n);
            over(&mut c, [255.0; 3], body);
            let flap = segment(p, flap_l, flap_m).min(segment(p, flap_m, flap_r)) - stroke / 2.0;
            over(&mut c, teal, coverage(flap * n).min(body));
            out.extend(c[..3].iter().map(|v| v.round().clamp(0.0, 255.0) as u8));
            out.push((c[3] * 255.0).round().clamp(0.0, 255.0) as u8);
        }
    }
    out
}

/// The same drawing as an SVG (hicolor `scalable`), on a 1024 canvas.
pub fn svg() -> String {
    let s = |v: f32| format!("{:.1}", v * 1024.0);
    let hex = |c: [f32; 3]| format!("#{:02x}{:02x}{:02x}", c[0] as u8, c[1] as u8, c[2] as u8);
    let (l, t) = (ENV_CX - ENV_HW + ENV_R * 0.5, ENV_CY - ENV_HH + ENV_R * 0.5);
    let r = ENV_CX + ENV_HW - ENV_R * 0.5;
    format!(
        r##"<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">
  <!-- Quatrelle app icon. Generated by `cargo xtask icons` (xtask/src/icons.rs); edit there. -->
  <defs>
    <linearGradient id="teal" x1="0" y1="{m}" x2="0" y2="{m2}" gradientUnits="userSpaceOnUse">
      <stop offset="0" stop-color="{top}"/>
      <stop offset="1" stop-color="{bottom}"/>
    </linearGradient>
  </defs>
  <rect x="{m}" y="{m}" width="{side}" height="{side}" rx="{rad}" fill="url(#teal)"/>
  <rect x="{ex}" y="{ey}" width="{ew}" height="{eh}" rx="{er}" fill="#ffffff"/>
  <polyline points="{l},{t} {cx},{fy} {r},{t}" fill="none" stroke="url(#teal)" stroke-width="{sw}" stroke-linecap="round" stroke-linejoin="round"/>
</svg>
"##,
        m = s(MARGIN),
        m2 = s(1.0 - MARGIN),
        top = hex(TOP),
        bottom = hex(BOTTOM),
        side = s(1.0 - 2.0 * MARGIN),
        rad = s(RADIUS),
        ex = s(ENV_CX - ENV_HW),
        ey = s(ENV_CY - ENV_HH),
        ew = s(2.0 * ENV_HW),
        eh = s(2.0 * ENV_HH),
        er = s(ENV_R),
        l = s(l),
        t = s(t),
        cx = s(ENV_CX),
        fy = s(FLAP_Y),
        r = s(r),
        sw = s(STROKE),
    )
}

/// RGBA bytes as a PNG file.
pub fn png(size: u32, rgba: &[u8]) -> Result<Vec<u8>, String> {
    let mut out = Vec::new();
    let mut enc = png::Encoder::new(&mut out, size, size);
    enc.set_color(png::ColorType::Rgba);
    enc.set_depth(png::BitDepth::Eight);
    enc.set_compression(png::Compression::High);
    let mut w = enc.write_header().map_err(|e| format!("png: {e}"))?;
    w.write_image_data(rgba).map_err(|e| format!("png: {e}"))?;
    w.finish().map_err(|e| format!("png: {e}"))?;
    Ok(out)
}

/// An `.icns` file from PNGs keyed by pixel size. macOS reads PNG data in every entry type used here.
pub fn icns(pngs: &[(u32, Vec<u8>)]) -> Result<Vec<u8>, String> {
    // (entry type, pixel size): 1x and @2x variants of 16–512 pt.
    const TYPES: &[(&[u8; 4], u32)] = &[
        (b"icp4", 16),
        (b"ic11", 32),
        (b"icp5", 32),
        (b"ic12", 64),
        (b"ic07", 128),
        (b"ic13", 256),
        (b"ic08", 256),
        (b"ic14", 512),
        (b"ic09", 512),
        (b"ic10", 1024),
    ];
    let mut body = Vec::new();
    for (kind, size) in TYPES {
        let png = pngs.iter().find(|(s, _)| s == size).map(|(_, p)| p).ok_or(format!("icns: no {size} px image"))?;
        body.extend_from_slice(*kind);
        body.extend_from_slice(&u32::try_from(png.len() + 8).map_err(|_| "icns: image too large")?.to_be_bytes());
        body.extend_from_slice(png);
    }
    let mut out = b"icns".to_vec();
    out.extend_from_slice(&u32::try_from(body.len() + 8).map_err(|_| "icns: too large")?.to_be_bytes());
    out.extend_from_slice(&body);
    Ok(out)
}

fn write(path: &Path, bytes: &[u8]) -> Result<(), String> {
    if let Some(dir) = path.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
    }
    std::fs::write(path, bytes).map_err(|e| format!("write {}: {e}", path.display()))?;
    println!("wrote {}", path.display());
    Ok(())
}

/// The owner's own picture, `assets/icon.png`, decoded to `(side, RGBA)`: square only, and an
/// 8-bit truecolour PNG (what every picture editor writes). `None` when it isn't there, which is
/// the drawing's turn.
fn provided(root: &Path) -> Option<(u32, Vec<u8>)> {
    let path = root.join("assets").join("icon.png");
    let bytes = std::fs::read(&path).ok()?;
    let mut reader = png::Decoder::new(std::io::Cursor::new(bytes));
    reader.set_transformations(png::Transformations::normalize_to_color8());
    let mut reader = match reader.read_info() {
        Ok(r) => r,
        Err(e) => {
            println!("{}: not a picture ({e}); the drawing is used", path.display());
            return None;
        }
    };
    let mut buf = vec![0; reader.output_buffer_size()?];
    let frame = reader.next_frame(&mut buf).ok()?;
    let (w, h) = (frame.width, frame.height);
    if w == 0 || h == 0 || w != h || w < 256 {
        println!("{}: {}×{}, a square of 256 px or more is needed; the drawing is used", path.display(), w, h);
        return None;
    }
    let pixels = match frame.color_type {
        png::ColorType::Rgba => buf,
        png::ColorType::Rgb => {
            let mut rgba = Vec::with_capacity(buf.len() / 3 * 4);
            for px in buf.as_chunks::<3>().0 {
                rgba.extend_from_slice(&[px[0], px[1], px[2], 0xff]);
            }
            rgba
        }
        other => {
            println!("{}: {other:?} isn't supported; the drawing is used", path.display());
            return None;
        }
    };
    let need = (w as usize).checked_mul(h as usize)?.checked_mul(4)?;
    if pixels.len() < need {
        return None;
    }
    Some((w, pixels))
}

/// `src` (`side`×`side`, RGBA) sampled down to `n`×`n`: each pixel is the average of the source
/// pixels under it, weighted by alpha, so a picture stays smooth at 16 px.
fn resized(src: &[u8], side: u32, n: u32) -> Vec<u8> {
    let mut out = vec![0u8; (n * n * 4) as usize];
    let s = u64::from(side);
    let d = u64::from(n);
    for y in 0..d {
        let y0 = y * s / d;
        let y1 = ((y + 1) * s / d).max(y0 + 1).min(s);
        for x in 0..d {
            let x0 = x * s / d;
            let x1 = ((x + 1) * s / d).max(x0 + 1).min(s);
            let (mut r, mut g, mut b, mut a, mut weight) = (0u64, 0u64, 0u64, 0u64, 0u64);
            for sy in y0..y1 {
                for sx in x0..x1 {
                    let i = ((sy * s + sx) * 4) as usize;
                    let Some(px) = src.get(i..i + 4) else { continue };
                    let alpha = u64::from(px[3]);
                    r += u64::from(px[0]) * alpha;
                    g += u64::from(px[1]) * alpha;
                    b += u64::from(px[2]) * alpha;
                    a += alpha;
                    weight += 1;
                }
            }
            let o = ((y * d + x) * 4) as usize;
            if weight == 0 || a == 0 {
                continue;
            }
            let mean = a; // premultiplied sums, divided by the alpha they carry
            out[o] = (r / mean).min(255) as u8;
            out[o + 1] = (g / mean).min(255) as u8;
            out[o + 2] = (b / mean).min(255) as u8;
            out[o + 3] = (a / weight).min(255) as u8;
        }
    }
    out
}

/// An SVG of `n`×`n` carrying `png` as it is: the scalable icon of a picture no drawing describes.
fn svg_of(png: &[u8], n: u32) -> String {
    const T: &[u8] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut b64 = String::with_capacity(png.len().div_ceil(3) * 4);
    for c in png.chunks(3) {
        let p = [c[0], c.get(1).copied().unwrap_or(0), c.get(2).copied().unwrap_or(0)];
        let v = (u32::from(p[0]) << 16) | (u32::from(p[1]) << 8) | u32::from(p[2]);
        for i in 0..4 {
            if i <= c.len() {
                b64.push(T[((v >> (18 - 6 * i)) & 63) as usize] as char);
            } else {
                b64.push('=');
            }
        }
    }
    format!(
        "<svg xmlns=\"http://www.w3.org/2000/svg\" xmlns:xlink=\"http://www.w3.org/1999/xlink\" \
         viewBox=\"0 0 {n} {n}\" width=\"{n}\" height=\"{n}\">\
         <image width=\"{n}\" height=\"{n}\" xlink:href=\"data:image/png;base64,{b64}\"/></svg>\n"
    )
}

pub fn run(root: &Path) -> Result<(), String> {
    let picture = provided(root);
    if picture.is_some() {
        println!("assets/icon.png is the source");
    }
    let dir = root.join("assets").join("app-icon");
    let mut pngs: Vec<(u32, Vec<u8>)> = Vec::new();
    for size in HICOLOR.iter().copied().chain([1024]) {
        let pixels = match &picture {
            Some((side, rgba)) => resized(rgba, *side, size),
            None => render(size),
        };
        pngs.push((size, png(size, &pixels)?));
    }
    for (size, bytes) in &pngs {
        if *size == 1024 {
            write(&dir.join("quatrelle-1024.png"), bytes)?;
        } else {
            write(&dir.join(format!("hicolor/{size}x{size}/apps/{ID}.png")), bytes)?;
        }
    }
    let scalable = match &picture {
        Some((side, rgba)) => svg_of(&png(512, &resized(rgba, *side, 512))?, 512).into_bytes(),
        None => svg().into_bytes(),
    };
    write(&dir.join(format!("hicolor/scalable/apps/{ID}.svg")), &scalable)?;
    let ico: Vec<Vec<u8>> = ICO.iter().filter_map(|s| pngs.iter().find(|(p, _)| p == s).map(|(_, b)| b.clone())).collect();
    write(&dir.join("quatrelle.ico"), &crate::ico::pack(&ico)?)?;
    write(&dir.join("quatrelle.icns"), &icns(&pngs)?)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn pixel(rgba: &[u8], size: u32, x: u32, y: u32) -> &[u8] {
        let i = ((y * size + x) * 4) as usize;
        &rgba[i..i + 4]
    }

    #[test]
    fn draws_a_teal_square_with_a_white_envelope() {
        let n = 256;
        let img = render(n);
        assert_eq!(img.len(), (n * n * 4) as usize);
        // Corners are transparent (rounded, with a margin).
        assert_eq!(pixel(&img, n, 0, 0)[3], 0);
        assert_eq!(pixel(&img, n, n - 1, n - 1)[3], 0);
        // Inside the square, away from the envelope: opaque teal.
        let bg = pixel(&img, n, n / 2, n / 8);
        assert_eq!(bg[3], 255);
        assert!(bg[2] > bg[0] && bg[1] > bg[0], "{bg:?}");
        // The envelope's lower half is white.
        assert_eq!(pixel(&img, n, n / 2, (n as f32 * 0.68) as u32), &[255, 255, 255, 255]);
        // The flap's tip is teal on the envelope.
        let tip = pixel(&img, n, n / 2, (n as f32 * FLAP_Y) as u32);
        assert!(tip[0] < 100, "{tip:?}");
    }

    #[test]
    fn small_sizes_keep_the_flap() {
        let n = 16;
        let img = render(n);
        let darkest_in_envelope = (6..10).flat_map(|y| (5..11).map(move |x| (x, y))).map(|(x, y)| pixel(&img, n, x, y)[0]).min().unwrap_or(255);
        assert!(darkest_in_envelope < 160, "the flap disappears at 16 px");
    }

    #[test]
    fn packs_icns_entries() {
        let pngs: Vec<(u32, Vec<u8>)> = [16, 32, 64, 128, 256, 512, 1024].iter().map(|&s| (s, vec![s as u8; 3])).collect();
        let f = icns(&pngs).unwrap();
        assert_eq!(&f[..4], b"icns");
        assert_eq!(u32::from_be_bytes(f[4..8].try_into().unwrap()) as usize, f.len());
        assert_eq!(&f[8..12], b"icp4");
        assert_eq!(u32::from_be_bytes(f[12..16].try_into().unwrap()), 11);
        assert!(icns(&pngs[1..]).is_err());
    }

    #[test]
    fn svg_is_well_formed() {
        let s = svg();
        assert!(s.starts_with("<svg") && s.trim_end().ends_with("</svg>"));
        assert!(s.contains("#0e7c86") || s.contains("#169aa6"));
    }
}
